function renderActionEvidence(action) {
  const drawer = document.querySelector(".action-drawer");
  if (!drawer || !action) return;

  const latestAudit = action.audit || [];
  const payloadRows = Object.entries(action.payload || {})
    .filter(([, value]) => typeof value === "string" || typeof value === "number" || Array.isArray(value))
    .slice(0, 5)
    .map(([key, value]) => {
      const rendered = Array.isArray(value) ? value.join(", ") : String(value);
      return `<div><span>${key}</span><b>${rendered}</b></div>`;
    })
    .join("");

  drawer.innerHTML = `
    <button class="drawer-close" type="button" aria-label="Close action drawer">Close</button>
    <p class="eyebrow">Evidence-backed action</p>
    <h2>${action.title}</h2>
    <p>${action.payload?.reason || action.payload?.script || "Proofline generated this from customer evidence and policy rules."}</p>
    <div class="drawer-grid">
      <div><span>Status</span><b>${action.status.replaceAll("_", " ")}</b></div>
      <div><span>Type</span><b>${action.type.replaceAll("_", " ")}</b></div>
      <div><span>Approval</span><b>${action.approvalRequired ? "Required" : "Not required"}</b></div>
      <div><span>Priority</span><b>${action.priority}</b></div>
      ${payloadRows}
    </div>
    <div class="drawer-audit">
      <h3>Audit trail</h3>
      ${latestAudit
        .map(
          (item) => `
            <div>
              <b>${item.event}</b>
              <span>${new Date(item.at).toLocaleString()}</span>
              <p>${item.note}</p>
            </div>
          `,
        )
        .join("")}
    </div>
    <div class="reply-actions">
      <button type="button" data-drawer-command="approve">Approve</button>
      <button type="button" data-drawer-command="execute">Execute</button>
      <button type="button" data-drawer-command="hold">Hold</button>
    </div>
  `;
}

async function hydrateActionDrawer(actionId) {
  if (!actionId) return;
  try {
    const response = await fetch(`/api/actions/${actionId}`);
    if (!response.ok) return;
    const data = await response.json();
    renderActionEvidence(data.action);
  } catch {
    // Static fallback drawer is already visible.
  }
}

