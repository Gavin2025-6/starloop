async function postJson(url) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "content-type": "application/json" },
  });
  const data = await response.json();
  if (!response.ok) throw new Error(data.message || data.error || "Request failed.");
  return data;
}

function actionToRow(action) {
  const statusLabel = action.status.replaceAll("_", " ");
  return {
    id: action.id,
    title: action.title,
    text: action.payload?.reason || action.payload?.script || "Automation action generated from customer evidence and policy rules.",
    tags: [action.type.replaceAll("_", " "), statusLabel, action.approvalRequired ? "approval" : "ready"],
    tone: action.status === "executed" ? "good" : action.approvalRequired ? "danger" : "warn",
    action: action.status === "requires_approval" ? "Approve" : action.status === "approved" ? "Execute" : "Open",
    apiStatus: action.status,
  };
}

async function hydrateLiveQueue() {
  const liveModule = modules.find((module) => module.id === "live");
  if (!liveModule) return;

  try {
    const response = await fetch("/api/actions");
    if (!response.ok) throw new Error("API unavailable.");
    const data = await response.json();
    const actions = data.actions || [];
    const ready = actions.filter((action) => action.status === "ready").length;
    const approval = actions.filter((action) => action.status === "requires_approval").length;
    const executed = actions.filter((action) => action.status === "executed").length;

    liveModule.metrics = [
      ["API state", "Live", "local server connected"],
      ["Ready", String(ready), "actions"],
      ["Approval", String(approval), "need owner"],
      ["Executed", String(executed), "completed"],
    ];
    liveModule.rows = actions.map(actionToRow);
    liveModule.side = {
      title: "Latest audit trail",
      items: actions
        .slice(0, 4)
        .map((action) => [action.title, action.audit?.at(-1)?.event || "action.planned"]),
    };

    if (moduleSelect?.value === "live" || eyebrow.textContent === "Live Queue") {
      suppressLiveHydrate = true;
      renderModule(liveModule);
      suppressLiveHydrate = false;
    }
  } catch {
    showToast("Live API unavailable. Static demo still works.");
  }
}

document.addEventListener("click", async (event) => {
  const close = event.target.closest(".drawer-close");
  if (close) {
    close.closest(".action-drawer").classList.remove("is-open");
    return;
  }

  const command = event.target.closest("[data-drawer-command]");
  if (!command) return;
  const label = command.dataset.drawerCommand;
  const drawer = command.closest(".action-drawer");
  const actionId = drawer?.dataset.actionId;

  if (actionId && label === "approve") {
    try {
      await postJson(`/api/actions/${actionId}/approve`);
      showToast("Approved through the local API.");
      await hydrateLiveQueue();
      return;
    } catch (error) {
      showToast(error.message);
      return;
    }
  }

  if (actionId && label === "execute") {
    try {
      await postJson(`/api/actions/${actionId}/execute`);
      showToast("Executed through the local API.");
      await hydrateLiveQueue();
      return;
    } catch (error) {
      showToast(error.message);
      return;
    }
  }

  showToast(label === "approve" ? "Approved in demo mode." : label === "execute" ? "Executed in demo mode." : "Action held for later.");
});

